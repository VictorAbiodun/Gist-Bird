// Generates supabase/seed/campus.sql from src/data/campus.json so the DB graph and the app graph never drift.
import fs from 'node:fs';
const data = JSON.parse(fs.readFileSync(new URL('../src/data/campus.json', import.meta.url), 'utf8'));
const by = Object.fromEntries(data.spots.map((s) => [s.id, s]));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
let sql = '-- GENERATED by scripts/gen-campus-sql.mjs. Do not edit by hand.\n';
sql += 'insert into public.campus_spots (id, name, kind, x, y) values\n';
sql += data.spots.map((s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.kind)}, ${s.x}, ${s.y})`).join(',\n') + '\non conflict (id) do update set name = excluded.name, kind = excluded.kind, x = excluded.x, y = excluded.y;\n';
sql += 'delete from public.campus_edges;\n';
sql += 'insert into public.campus_edges (a, b, dist) values\n';
sql += data.edges.map(([a, b]) => {
  const d = Math.hypot(by[a].x - by[b].x, by[a].y - by[b].y);
  return `  (${q(a)}, ${q(b)}, ${d.toFixed(1)})`;
}).join(',\n') + ';\n';
fs.mkdirSync(new URL('../supabase/seed/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../supabase/seed/campus.sql', import.meta.url), sql);
console.log('wrote supabase/seed/campus.sql');
